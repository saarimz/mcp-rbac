/**
 * Write policy/mcp-rbac.yaml from catalog/klaviyo-tools.json + src/roles.ts.
 * Run: npx tsx src/generate-policy.ts
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCatalog, marketerAllowed, supportAllowed, toolNameAliases, type CatalogTool } from "./roles.ts";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "policy", "mcp-rbac.yaml");

function yamlList(items: string[], indent: number): string {
  const pad = " ".repeat(indent);
  return items.map((s) => `${pad}- ${s}`).join("\n");
}

function names(tools: CatalogTool[], pred: (t: CatalogTool) => boolean): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const t of tools.filter(pred)) {
    for (const n of toolNameAliases(t.name)) {
      if (!seen.has(n)) { seen.add(n); out.push(n); }
    }
  }
  return out;
}

const catalog = loadCatalog();
const marketer = names(catalog.tools, marketerAllowed);
const support = names(catalog.tools, supportAllowed);

const yaml = `# mcp-rbac policy for the official Klaviyo MCP tool catalog (${catalog.count} tools).
# Generated by src/generate-policy.ts from catalog/klaviyo-tools.json
# (https://developers.klaviyo.com/en/docs/klaviyo_mcp_server_available_tools,
# retrieved ${catalog.retrievedAt ?? "unknown"}). Do not edit by hand; regenerate.
#
# Roles:
# - owner: all tools
# - marketer: reads in campaign-adjacent categories, plus create/update of
#   campaign / template / segment drafts. No deletes, no sending.
# - support: read-only Profiles and Events tools.
version: 1
name: klaviyo-e2e
description: Guard in front of Klaviyo MCP (hosted or local klaviyo-mcp-server).
$schema: ../../../spec/mcp-rbac.schema.json

roles:
  owner:
    description: Full access to every Klaviyo MCP tool. The live driver still never sends, deletes, or previews-sends.
    tools:
      - "*"
  marketer:
    description: Read campaign-adjacent data and create or update campaign, template, and segment drafts. No deletes, no sending.
    tools:
${yamlList(marketer, 6)}
  support:
    description: Read-only access to profile and event tools.
    tools:
${yamlList(support, 6)}
`;

writeFileSync(outPath, yaml);
process.stderr.write(`wrote ${outPath} (marketer ${marketer.length} tools, support ${support.length} tools, owner *)\n`);
