import { classifyTool, type Risk } from "./classify.js";
import type { Inventory } from "./introspect.js";
import { isValidToolName } from "./patterns.js";
import type { PolicyFile } from "./policy.js";

export interface Plan {
  read: string[]; write: string[]; destructive: string[];
  resources: string[]; prompts: string[];
  skipped: { name: string; reason: string }[];
  rows: { name: string; risk: Risk; why: string }[];
}

const resourceName = (n: string) => (isValidToolName(n) ? n : null);

export function plan(inv: Inventory): Plan {
  const p: Plan = { read: [], write: [], destructive: [], resources: [], prompts: [], skipped: [], rows: [] };
  for (const t of inv.tools) {
    if (!isValidToolName(t.name)) { p.skipped.push({ name: t.name, reason: "tool name has characters mcp-rbac can't match (allowed: A-Z a-z 0-9 _ - .)" }); continue; }
    const c = classifyTool(t);
    p[c.risk].push(t.name);
    p.rows.push({ name: t.name, ...c });
  }
  for (const r of [...inv.resourceTemplates, ...inv.resources]) {
    const n = resourceName(r.name);
    if (n) { if (!p.resources.includes(n)) p.resources.push(n); }
    else p.skipped.push({ name: r.name, reason: "resource name isn't a valid policy name; the proxy will slug it" });
  }
  for (const pr of inv.prompts) {
    if (isValidToolName(pr.name)) p.prompts.push(pr.name);
    else p.skipped.push({ name: pr.name, reason: "prompt name isn't a valid policy name" });
  }
  return p;
}

export function toJsonPolicy(inv: Inventory): PolicyFile & { description: string } {
  const p = plan(inv);
  return {
    description: `Starter policy generated by mcp-rbac init for ${inv.server.name}@${inv.server.version}. Review before use.`,
    version: 1,
    roles: {
      viewer: { tools: p.read, resources: p.resources, prompts: p.prompts },
      operator: { tools: [...p.read, ...p.write], resources: p.resources, prompts: p.prompts },
      admin: { tools: ["*"], resources: ["*"], prompts: ["*"] },
    },
    approve: p.destructive,
    limits: p.destructive.map((tool) => ({ tool, max: 5, windowMs: 86_400_000 })),
  };
}

const q = (s: string) => JSON.stringify(s);
const chain = (method: string, names: string[], indent: string) => (names.length ? `\n${indent}.${method}(${names.map(q).join(", ")})` : "");

export function toTsPolicy(inv: Inventory, source: string, pkg = "mcp-rbac"): string {
  const p = plan(inv);
  const width = Math.max(4, ...p.rows.map((r) => r.name.length));
  const inventory = p.rows.map((r) => `//   ${r.name.padEnd(width)}  ${r.risk.padEnd(11)} ${r.why}`).join("\n");
  const skipped = p.skipped.map((s) => `//   SKIPPED ${q(s.name)}: ${s.reason}`).join("\n");
  const I = "    ";
  return `// Starter policy generated by \`mcp-rbac init\` from ${source}
// Server: ${inv.server.name}@${inv.server.version}. Generated ${new Date().toISOString().slice(0, 10)}.
// REVIEW BEFORE USE: risk classes are heuristics (tool names + self-declared annotations).
//
// Tool inventory:
${inventory || "//   (no tools)"}
${skipped ? skipped + "\n" : ""}
import { role, type RateLimit } from ${q(pkg)};

/** Edit to match your tenancy model, e.g. { org: string; project?: string }. */
export type Resource = { tenant?: string };

export const roles = {
  /** read-only tools, resources and prompts */
  viewer: role<Resource>()${chain("can", p.read, I)}${chain("resources", p.resources, I)}${chain("prompts", p.prompts, I)},
  /** viewer + tools that change state (not destructive) */
  operator: role<Resource>()${chain("can", [...p.read, ...p.write], I)}${chain("resources", p.resources, I)}${chain("prompts", p.prompts, I)},
  /** everything, including destructive tools (which still need approval) */
  admin: role<Resource>().can("*").resources("*").prompts("*"),
};

/** Destructive tools need a human to approve each call. */
export const approve: string[] = ${JSON.stringify(p.destructive)};

/** At most 5 destructive calls per delegation tree per day. */
export const limits: RateLimit[] = ${JSON.stringify(p.destructive.map((tool) => ({ tool, max: 5, windowMs: 86_400_000 })))};
`;
}
